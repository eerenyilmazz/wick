2. TOPLANAN KISISEL VERILER
Uygulamayi kullanirken asagidaki kisisel verileriniz toplanir:
- Kimlik ve iletisim bilgileri: ad-soyad, e-posta adresi
- Profil bilgileri: dogum tarihi, cinsiyet, biyografi, ilgi alanlari, il/ilce bilgisi
- Gorsel veriler: profil fotograflari
- Iletisim icerigi: eslesilen kullanicilarla yapilan mesajlasmalar
- Islem verileri: begeni/gecme tercihleri, eslesme gecmisi, jeton bakiyesi ve satin alma gecmisi
- Teknik veriler: cihaz bilgisi, IP adresi, oturum ve guvenlik loglari, uygulama kullanim istatistikleri

3. KISISEL VERILERIN ISLENME AMACI
Kisisel verileriniz; hesabinizin olusturulmasi ve yonetimi, eslestirme algoritmasinin calistirilmasi, kullanicilar arasi iletisimin saglanmasi, dolandiricilik ve kotuye kullanimin onlenmesi, sahte/cift hesaplarin tespiti, yasal yukumluluklerin yerine getirilmesi, musteri destegi saglanmasi ve hizmet kalitesinin artirilmasi amaciyla islenir.

4. OTOMATIK KARAR VERME VE PROFILLEME
