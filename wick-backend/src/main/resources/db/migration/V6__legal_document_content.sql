4. KULLANICI YUKUMLULUKLERI
Kullanicilar; baskasi adina sahte profil olusturamaz, taciz, nefret soylemi, ayrimcilik veya tehdit iceren davranislarda bulunamaz, ticari amacli izinsiz tanitim yapamaz ve diger kullanicilarin kisisel bilgilerini izinsiz paylasamaz. Bu kurallarin ihlali hesabin askiya alinmasi veya kalici olarak kapatilmasi ile sonuclanabilir.

