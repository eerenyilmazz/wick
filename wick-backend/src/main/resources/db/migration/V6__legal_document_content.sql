GIZLILIK POLITIKASI VE KVKK AYDINLATMA METNI

1. VERI SORUMLUSU
Wick uygulamasi ("Wick", "uygulama", "biz"), 6698 sayili Kisisel Verilerin Korunmasi Kanunu ("KVKK") kapsaminda veri sorumlusu sifatiyla, asagida belirtilen kisisel verilerinizi isbu metinde aciklanan amac ve kapsamda islemektedir.

2. TOPLANAN KISISEL VERILER
Uygulamayi kullanirken asagidaki kisisel verileriniz toplanir:
- Kimlik ve iletisim bilgileri: ad-soyad, e-posta adresi
- Profil bilgileri: dogum tarihi, cinsiyet, biyografi, ilgi alanlari, il/ilce bilgisi
- Gorsel veriler: profil fotograflari
- Iletisim icerigi: eslesilen kullanicilarla yapilan mesajlasmalar
- Islem verileri: begeni/gecme tercihleri, eslesme gecmisi, jeton bakiyesi ve satin alma gecmisi
- Teknik veriler: cihaz bilgisi, IP adresi, oturum ve guvenlik loglari

3. KISISEL VERILERIN ISLENME AMACI
Kisisel verileriniz; hesabinizin olusturulmasi ve yonetimi, eslestirme algoritmasinin calistirilmasi, kullanicilar arasi iletisimin saglanmasi, dolandiricilik ve kotuye kullanimin onlenmesi, yasal yukumluluklerin yerine getirilmesi ve hizmet kalitesinin artirilmasi amaciyla islenir.

4. HUKUKI SEBEP
Kisisel verileriniz, KVKK'nin 5. maddesinde yer alan "bir sozlesmenin kurulmasi veya ifasiyla dogrudan dogruya ilgili olma", "veri sorumlusunun hukuki yukumlulugunu yerine getirebilmesi icin zorunlu olma" ve acik riza gerektiren hallerde acik rizaniza dayanilarak islenmektedir.

5. KISISEL VERILERIN PAYLASILMASI
Kisisel verileriniz, yasal zorunluluklar disinda ucuncu taraflarla paylasilmaz. Barindirma ve altyapi hizmeti aldigimiz tedarikciler, yalnizca hizmetin verilmesi icin gerekli oldugu olcude ve gizlilik yukumlulugu altinda veriye erisebilir.

6. VERI SAKLAMA SURESI
Kisisel verileriniz, hesabiniz aktif oldugu surece ve hesap silindikten sonra yasal saklama yukumluluklerinin gerektirdigi sure kadar saklanir; bu surenin sonunda silinir veya anonim hale getirilir.

7. KVKK MADDE 11 KAPSAMINDAKI HAKLARINIZ
Kisisel verisi islenen ilgili kisi olarak; kisisel verinizin islenip islenmedigini ogrenme, islenmisse buna iliskin bilgi talep etme, islenme amacina uygun kullanilip kullanilmadigini ogrenme, yurt ici/yurt disinda aktarildigi ucuncu kisileri bilme, eksik/yanlis islenmisse duzeltilmesini isteme, silinmesini/yok edilmesini isteme, islenen verilerin munhasiran otomatik sistemler vasitasiyla analiz edilmesi suretiyle aleyhinize bir sonucun ortaya cikmasina itiraz etme ve kanuna aykiri islenme nedeniyle zarara ugramaniz halinde zararin giderilmesini talep etme haklarina sahipsiniz.

8. VERI GUVENLIGI
Kisisel verilerinizin guvenligini saglamak icin sifreleme, erisim kontrolu ve duzenli guvenlik denetimleri dahil olmak uzere gerekli teknik ve idari tedbirler alinmaktadir.

9. ILETISIM
Yukaridaki haklariniza iliskin taleplerinizi uygulama icindeki destek kanallari uzerinden iletebilirsiniz.

